const zh: Dict = {}

function activeLocale(): 'zh' | 'en' {
  return resolvedLocale().toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** Translate a Chinese source string. Unknown strings fall back to the source. */
export function t(text: string): string {
  if (activeLocale() === 'zh') return zh[text] ?? text
  return en[text] ?? text
}

/** Translate, then replace {name} placeholders. */
export function tWith(text: string, values: Record<string, string | number>): string {
  return t(text).replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`))
}
